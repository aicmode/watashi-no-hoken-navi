/**
 * 「例え（アナロジー）」定義。
 *
 * 保険そのものを説明する前に、ユーザーが自分にとって身近な世界を選ぶ。
 * 選んだ例えは、体験全体（比喩パネル・備えカード）の言葉づかいに反映される。
 *
 * 4種類目・5種類目（✈️ 旅行 / 🎮 ゲーム / ⚽ スポーツ など）を足す場合も、
 * この配列に1件追加するだけでよい。UI 側の変更は不要。
 *
 * 文章の作り方（各パターン共通の3段階）:
 *   1. metaphor … 身近な例えの話
 *   2. life     … 暮らしへの橋渡し
 *   3. bridge   … 備えについて考えるきっかけ
 *
 * 断定的な推奨表現（必要です／おすすめです）や、
 * 根拠のない一般化（ほとんどの人／多くの人／○％）は使わない。
 */

export type AnalogyId = "car" | "phone" | "home";

/** 「例え × ライフイベント」1パターン分の説明 */
export type AnalogyStory = {
  /** 身近な例えの見出し */
  heading: string;
  /** 身近な例えの本文 */
  body: string;
  /** 暮らしへの橋渡し */
  lifeBody: string;
  /** 備えについて考えるきっかけ（締めの1文） */
  bridge: string;
};

export type Analogy = {
  id: AnalogyId;
  emoji: string;
  /** 例えの名前（「クルマ」など） */
  title: string;
  /** 選択カードに添える1行説明 */
  shortDescription: string;
  /** この例えの世界観を表すキーワード */
  keywords: string[];
  /** 比喩パネル左側のバッジ表記（「クルマなら」など） */
  worldBadge: string;
  /** 比喩パネル右側（暮らし側）の見出し */
  lifeHeading: string;
  /** 「備え」一覧の導入文（この例えの世界での "眺め方"） */
  browseLead: string;
  /** ライフイベントごとの説明（全イベント分を必ず持つ） */
  lifeEventStories: Record<LifeEventId, AnalogyStory>;
  /** 「備え」カードを、この例えの世界で言い換えたもの */
  coverageAnalogies: Record<CoverageId, string>;
};

